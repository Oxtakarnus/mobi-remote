class Volume:
    """볼륨 자료 하나 → 속성별 키 [(Time, 값)] (Time 순)."""

    def __init__(self, data: dict):
        self.tracks: dict[str, list[tuple[float, object]]] = {}
        for kf in ((data or {}).get("GlobalGroup") or {}).get("KeyFrames") or []:
            t = float(kf.get("Time") or 0.0)
            for grp, d in kf.items():
                if grp == "Time" or not isinstance(d, dict):
                    continue
                for k, v in d.items():
                    if v is not None:
                        self.tracks.setdefault(f"{grp}.{k}", []).append((t, v))
        for keys in self.tracks.values():
            keys.sort(key=lambda a: a[0])

    def at(self, t: float) -> dict:
        """하루 중 시각 t 의 값 전부 {"묶음.속성": 값}."""
        return {k: sample(keys, t, rot=k.endswith("Rotation")) for k, keys in self.tracks.items()}


def sample(keys: list, t: float, rot: bool = False):
    """키 [(Time, 값)] 의 시각 t 값. 키 사이는 선형(rot 이면 쿼터니언 slerp), 하루 주기라 끝과 처음을 잇는다."""
    if not keys:
        return None
    if len(keys) == 1:
        return keys[0][1]
    t = float(t) % 1.0
    times = [k[0] for k in keys]
    i = bisect.bisect_right(times, t)
    if i == 0:
        (ta, a), (tb, b) = (keys[-1][0] - 1.0, keys[-1][1]), keys[0]
    elif i == len(keys):
        (ta, a), (tb, b) = keys[-1], (keys[0][0] + 1.0, keys[0][1])
    else:
        (ta, a), (tb, b) = keys[i - 1], keys[i]
    f = 0.0 if tb <= ta else (t - ta) / (tb - ta)
    return _mix(a, b, f, rot)


def _num(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _mix(a, b, f: float, rot: bool):
    if _num(a) and _num(b):
        return a + (b - a) * f
    if isinstance(a, list) and isinstance(b, list) and len(a) == len(b) and all(map(_num, a + b)):
        if rot and len(a) == 4:
            return slerp(a, b, f)
        return [x + (y - x) * f for x, y in zip(a, b)]
    return a if f < 0.5 else b


def slerp(a, b, f: float) -> list[float]:
    qa, qb = np.asarray(a, float), np.asarray(b, float)
    qa, qb = qa / (np.linalg.norm(qa) or 1.0), qb / (np.linalg.norm(qb) or 1.0)
    d = float(qa @ qb)
    if d < 0:
        qb, d = -qb, -d
    if d > 0.9995:
        q = qa + (qb - qa) * f
    else:
        th = math.acos(min(1.0, d))
        q = (math.sin((1 - f) * th) * qa + math.sin(f * th) * qb) / math.sin(th)
    return [float(x) for x in q / (np.linalg.norm(q) or 1.0)]


def forward(q) -> list[float]:
    """쿼터니언 (x, y, z, w) 이 돌린 앞 방향 q·(0,0,1) (Unity 축)."""
    x, y, z, w = (float(v) for v in q)
    return [2 * (x * z + w * y), 2 * (y * z - w * x), 1 - 2 * (x * x + y * y)]


def to_viewer(v) -> list[float]:
    """Unity 축 점·방향 → 뷰어 축 (x 뒤집음)."""
    return [-float(v[0]), float(v[1]), float(v[2])]


def light_direction(q) -> list[float]:
    """MainLight.Rotation → 뷰어 축의 빛 쪽 단위 벡터."""
    f = np.asarray(forward(q))
    f = f / (np.linalg.norm(f) or 1.0)
    return to_viewer(-f)


def _rgb(v, fill=0.0) -> list[float]:
    v = list(v) if isinstance(v, list) else [fill] * 3
    return [float(x) for x in (v + [fill] * 3)[:3]]


def _alpha(v) -> float:
    return float(v[3]) if isinstance(v, list) and len(v) > 3 else 1.0


def srgb(c: float) -> float:
    """선형 → sRGB (0..1)."""
    c = min(1.0, max(0.0, float(c)))
    return c * 12.92 if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def linear(c: float) -> float:
    """sRGB → 선형 (0..1)."""
    c = min(1.0, max(0.0, float(c)))
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def flat_sh(v: float = 1.0) -> dict:
    """방향과 상관없는 SH (상수만)."""
    z = [0.0, 0.0, 0.0]
    return {"constant": [v, v, v], **{k: list(z) for k in ("x", "y", "z", "xy", "yz", "zz", "xz", "c")}}


def preset(raw: dict) -> dict:
    """볼륨 한 시각의 값 → 뷰어 조명 꼴."""
    g = lambda k, d=None: raw.get(k, d)   # noqa: E731
    inten = float(g("MainLight.Intensity", 1.0))
    direct = [c * inten for c in _rgb(g("MainLight.Color"), 1.0)]
    indirect = _rgb(g("GlobalEnvironment.GILightColor"), 0.0)
    out = {
        "direction": light_direction(g("MainLight.Rotation", [0.0, 0.0, 0.0, 1.0])),
        "direct": direct,
        "indirect": indirect,
        "shadow_strength": float(g("MainLight.ShadowIntensity", 1.0)),
        "night2day": float(g("GlobalEnvironment.Night2Day", 1.0)),
        "silhouette": [float(x) for x in (list(g("CharacterLight.SilhouetteColor") or []) + [0.0] * 4)[:4]],
        "fog": {"color": _rgb(g("GlobalEnvironment.FogColor")),
                "start": float(g("GlobalEnvironment.FogStartDistance", 0.0)),
                "end": float(g("GlobalEnvironment.FogEndDistance", 1000.0)),
                "dim_range": float(g("GlobalEnvironment.DimFogRange", 1000.0)),
                "dim_power": float(g("GlobalEnvironment.DimFogPower", 1.0))},
        "sky": {"top": _rgb(g("Skybox.SkyColorTop")), "middle": _rgb(g("Skybox.SkyColorMiddle")),
                "bottom": _rgb(g("Skybox.SkyColorBottom")),
                "positions": [float(g(f"Skybox.SkyPosition{i}", 0.0)) for i in range(1, 5)]},
        "gradient": {"dark": _rgb(g("PostProcessing.AmbientGradientDarkSideColor"), 1.0),
                     "light": _rgb(g("PostProcessing.AmbientGradientLightSideColor"), 0.0),
                     "main": list(direct)},
        "ambient_sh": flat_sh(),
        "lights": [],
    }
    out["background_srgb"] = [srgb(c) for c in out["fog"]["color"]]
    lc, gc = g("CharacterLight.LightColor"), g("CharacterLight.GIColor")
    la, ga = (min(1.0, max(0.0, _alpha(v))) if isinstance(v, list) else 0.0 for v in (lc, gc))
    if la > 0 or ga > 0:
        out["character_light"] = {
            "direct": [d + (c - d) * la for d, c in zip(direct, _rgb(lc))],
            "indirect": [d + (c - d) * ga for d, c in zip(indirect, _rgb(gc))],
        }
    return out


def read_volume(res: gf.Resources, name: str) -> Volume:
    want = f"VolumeData/{name}.volume.sjon.bin"
    path = want if want in res.paths else res.find("/" + want.rsplit("/", 1)[-1])
    if path is None:
        raise StageError(f"볼륨 자료를 찾지 못했습니다: {name}")
    return Volume(sjon.load(res.read(path)))


def presets(game_dir: Path, stage_lighting: dict | None = None) -> dict:
    """PRESETS → {"version", "presets": {이름: 조명}, "guess"}. stage_lighting(무대 조명·SH)은 rebirth 에 넣는다."""
    res = gf.Resources(Path(game_dir), lambda p: p.startswith("VolumeData/"))
    vols: dict[str, Volume] = {}
    out = {}
    for key, (vol, t, label) in PRESETS.items():
        if vol not in vols:
            vols[vol] = read_volume(res, vol)
        raw = vols[vol].at(t)
        p = preset(raw)
        if key == "rebirth" and stage_lighting:
            p["lights"] = list(stage_lighting.get("lights") or [])
            if stage_lighting.get("ambient_sh"):
                p["ambient_sh"] = stage_lighting["ambient_sh"]
        p.update(name=label, source={"volume": f"VolumeData/{vol}.volume.sjon.bin", "time": t}, raw=raw)
        out[key] = p
    return {"version": 1, "space": {"axes": "viewer", "color": "linear", "background": "srgb"},
            "presets": out, "guess": GUESS}


# ── SH ──
def sh_terms(coef) -> dict:
    """Unity SphericalHarmonicsL2 27 값(r0..r8, g0..g8, b0..b8) → SampleSH9 항별 계수 (뷰어 축).
    unity_SHA = (c3, c1, c2, c0 − c6), unity_SHB = (c4, c5, 3·c6, c7), unity_SHC = c8 (LightProbeUtility 와 같은 관례)."""
    c = np.asarray(coef, float).reshape(3, 9)
    t = {"constant": c[:, 0] - c[:, 6], "x": -c[:, 3], "y": c[:, 1], "z": c[:, 2],
         "xy": -c[:, 4], "yz": c[:, 5], "zz": 3 * c[:, 6], "xz": -c[:, 7], "c": c[:, 8]}
    return {k: [float(x) for x in v] for k, v in t.items()}


def eval_sh(terms: dict, n) -> list[float]:
    """뷰어 축 법선 n 의 SH 값 (뷰어 셰이더 studioSH 와 같은 식)."""
    x, y, z = (float(v) for v in n)
    a = lambda k: np.asarray(terms.get(k) or [0, 0, 0], float)   # noqa: E731
    v = (a("constant") + a("x") * x + a("y") * y + a("z") * z + a("xy") * x * y + a("yz") * y * z
         + a("zz") * z * z + a("xz") * x * z + a("c") * (x * x - y * y))
    return [float(c) for c in v]


_SH_KEY = re.compile(r"sh\[\s*(\d+)\]")


def probe_coefs(tree: dict) -> tuple[list, list]:
    """LightProbes typetree → (위치 [[x,y,z]] Unity 축, 계수 [[27]])."""
    pos = [[float(p["x"]), float(p["y"]), float(p["z"])] for p in (tree.get("m_Data") or {}).get("m_Positions") or []]
    coefs = []
    for c in tree.get("m_BakedCoefficients") or []:
        v = [0.0] * 27
        for k, x in (c.items() if isinstance(c, dict) else ()):
            m = _SH_KEY.fullmatch(k)
            if m and int(m.group(1)) < 27:
                v[int(m.group(1))] = float(x)
        coefs.append(v)
    return pos, coefs


# ── 무대 ──
def _trs(t, r, s) -> np.ndarray:
    x, y, z, w = (float(v) for v in r)
    rot = np.array([[1 - 2 * (y * y + z * z), 2 * (x * y - w * z), 2 * (x * z + w * y)],
                    [2 * (x * y + w * z), 1 - 2 * (x * x + z * z), 2 * (y * z - w * x)],
                    [2 * (x * z - w * y), 2 * (y * z + w * x), 1 - 2 * (x * x + y * y)]])
    m = np.eye(4)
    m[:3, :3] = rot * np.asarray(s, float)
    m[:3, 3] = t
    return m


def world_matrices(nodes: list[dict], base: np.ndarray | None = None) -> dict[str, np.ndarray]:
    """skeleton 노드 → path 별 월드 행렬 (base = 루트 GameObject 자기 행렬)."""
    base = np.eye(4) if base is None else base
    out: list[np.ndarray] = []
    for nd in nodes:
        par = out[nd["parent"]] if nd["parent"] >= 0 else base
        out.append(par @ _trs(nd["t"], nd["r"], nd["s"]))
    return {nd["path"]: m for nd, m in zip(nodes, out)}


def _walk(go):
    """GameObject 아래 전부 (자기 포함)."""
    yield go
    for o in A.components(go):
        if o.type.name == "Transform":
            for ch in o.read().m_Children:
                try:
                    yield from _walk(ch.deref().read().m_GameObject.deref().read())
                except Exception:
                    continue


def _pid(obj) -> int | None:
    rd = getattr(obj, "object_reader", None)
    return getattr(rd, "path_id", None)


def _cols(seq, n: int, k: int) -> np.ndarray | None:
    """정점 값 목록 → (n, k) f32. 성분이 더 많으면 앞 k 개만 (법선이 4성분으로 저장된 메시가 있다)."""
    if not seq or len(seq) != n:
        return None
    a = np.asarray(seq, np.float32).reshape(n, -1)
    if a.shape[1] < k:
        return None
    return np.ascontiguousarray(a[:, :k])


def static_mesh(mesh) -> dict | None:
    """뼈 없는 UnityPy Mesh → {pos, nrm, uv, uv1, col, tris(서브메시마다)}. 정점이 없으면 None."""
    from UnityPy.helpers.MeshHelper import MeshHandler
    h = MeshHandler(mesh)
    h.process()
    n = len(h.m_Vertices or [])
    pos = _cols(h.m_Vertices, n, 3)
    if not n or pos is None:
        return None
    nrm = _cols(h.m_Normals, n, 3)
    col = _cols(h.m_Colors, n, 4)
    if col is None and _cols(h.m_Colors, n, 3) is not None:
        col = np.c_[_cols(h.m_Colors, n, 3), np.ones(n, np.float32)].astype(np.float32)
    return {"pos": pos, "nrm": nrm if nrm is not None else np.zeros((n, 3), np.float32),
            "uv": _cols(h.m_UV0, n, 2), "uv1": _cols(h.m_UV1, n, 2),
            "col": None if col is None else np.clip(col, 0.0, 1.0), "tris": h.get_triangles()}


class StageExporter:
    """환생 무대 prefab → 모델 json·bin + 텍스처 png, 라이트 프로브 → ambient_sh."""

    def __init__(self, game_dir: Path, data_dir: Path):
        self.pack = A.AssetPack(Path(game_dir), Path(data_dir) / "stage", keep=lambda p: any(k in p for k in _KEEP))
        self.tex = T.TextureStore(Path(data_dir) / "tex")   # 텍스처 png 는 모델과 같은 폴더·규칙

    def _open(self, path: str):
        if path not in self.pack.paths:
            raise StageError(f"무대 자산을 찾지 못했습니다: {path.rsplit('/', 1)[-1]}")
        return self.pack.open([path], limit=60)

    def ambient_sh(self) -> dict | None:
        """무대 라이트 프로브 평균 SH (못 읽으면 None)."""
        try:
            env = self._open(PROBES)
        except StageError:
            return None
        for o in env.objects:
            if o.type.name == "LightProbes":
                _pos, coefs = probe_coefs(o.read_typetree())
                if coefs:
                    return sh_terms(np.mean(np.asarray(coefs, float), 0))
        return None

    def lighting(self) -> dict:
        """무대 조명·SH 만 (프리셋 rebirth 용)."""
        root, nodes, by_id, world = self._root()
        return {"lights": self._lights(root, by_id, world), "ambient_sh": self.ambient_sh()}

    def _root(self):
        env = self._open(PREFAB)
        gos = A.roots(env, PREFAB)
        if not gos:
            raise StageError("무대 prefab 을 읽지 못했습니다")
        root = gos[0]
        nodes, by_id = E.skeleton(root)
        base = None
        tp = E.transform_ptr(root)
        if tp is not None:
            t = tp.deref().read()
            q, v, s = t.m_LocalRotation, t.m_LocalPosition, t.m_LocalScale
            base = _trs([v.x, v.y, v.z], [q.x, q.y, q.z, q.w], [s.x, s.y, s.z])
            by_id.setdefault(tp.m_PathID, "")
        world = world_matrices(nodes, base)
        world[""] = base if base is not None else np.eye(4)
        return root, nodes, by_id, world

    def _lights(self, root, by_id: dict, world: dict) -> list[dict]:
        out = []
        for go in _walk(root):
            tp = E.transform_ptr(go)
            m = world.get(by_id.get(tp.m_PathID) if tp is not None else None)
            if m is None:
                continue
            for o in A.components(go):
                if o.type.name != "Light":
                    continue
                lt = o.read()
                kind = {0: "spot", 2: "point"}.get(int(lt.m_Type))
                if kind is None or not getattr(lt, "m_Enabled", 1):
                    continue
                c = lt.m_Color
                inten = float(lt.m_Intensity)
                d = {"name": go.m_Name, "kind": kind, "position": to_viewer(m[:3, 3]),
                     "color": [linear(v) * inten for v in (c.r, c.g, c.b)],   # URP: color.linear × intensity
                     "color_srgb": [float(c.r), float(c.g), float(c.b)], "intensity": inten,
                     "range": float(lt.m_Range), "layer": int(getattr(lt, "m_RenderingLayerMask", 0xFFFFFFFF))}
                if kind == "spot":
                    f = m[:3, 2] / (np.linalg.norm(m[:3, 2]) or 1.0)
                    outer = float(lt.m_SpotAngle)
                    inner = float(getattr(lt, "m_InnerSpotAngle", 0.0) or 0.0)
                    d.update(direction=to_viewer(-f), spot_angle=outer, inner_spot_angle=inner,
                             outer_cos=math.cos(math.radians(outer) / 2), inner_cos=math.cos(math.radians(inner) / 2))
                out.append(d)
        return out

    def _reflect(self, root) -> tuple[set[int], float]:
        """PlanarReflections 컴포넌트 → (반사할 렌더러 path id 들, ClipPlaneOffset)."""
        ids, off = set(), 0.0
        for go in _walk(root):
            for o in A.components(go):
                if o.type.name != "MonoBehaviour":
                    continue
                if A.script_name(o) != "PlanarReflections":
                    continue
                try:
                    t = o.read_typetree()
                except Exception:
                    continue
                ids |= {r["m_PathID"] for r in t.get("MeshRenderers") or []}
                off = float((t.get("Settings") or {}).get("ClipPlaneOffset", 0.0))
        return ids, off

    def export(self, out_json: Path) -> dict:
        root, nodes, by_id, world = self._root()
        reflect_ids, clip = self._reflect(root)
        out = E.Out()
        mats: list[dict] = []
        seen: dict[str, int] = {}
        meshes = []
        pts = []
        floor = None
        for go, r in A.renderers(root):
            mesh = E.mesh_of(go, r)
            src = static_mesh(mesh) if mesh is not None else None
            if src is None:
                continue
            n = len(src["pos"])
            groups = []
            for si, tris in enumerate(src["tris"]):
                if tris is None or not len(tris):
                    continue
                ptr = r.m_Materials[min(si, len(r.m_Materials) - 1)] if r.m_Materials else None
                mi = self._material(ptr, mats, seen)
                if mi is None:
                    continue
                t = np.asarray(tris, np.uint32).reshape(-1)
                groups.append({"mat": mi, "off": out.put(t), "count": int(t.size)})
            if not groups:
                continue
            tp = E.transform_ptr(go)
            node = by_id.get(tp.m_PathID) if tp is not None else None
            uv = src["uv"] if src["uv"] is not None else np.zeros((n, 2), np.float32)
            m = {"name": go.m_Name, "n": n, "pos": out.put(src["pos"]), "nrm": out.put(src["nrm"]), "uv": out.put(uv),
                 "groups": groups, "shapes": {}, "node": node or None,
                 "layer": int(getattr(r, "m_RenderingLayerMask", 1))}
            if src["uv1"] is not None:
                m["uv1"] = out.put(src["uv1"])
            if src["col"] is not None:
                m["col"] = out.put(src["col"])
            if _pid(r) in reflect_ids or any(mats[g["mat"]].get("reflect") for g in groups):
                m["reflect"] = True
            mw = world.get(node or "", np.eye(4))
            wp = (np.c_[src["pos"], np.ones(n)] @ mw.T)[:, :3]
            pts.append(wp)
            # 바닥 = 반사 원판 (없으면 이름이 _Floor 로 끝나는 메시)
            if floor is None and (m.get("reflect") or go.m_Name.endswith("_Floor")):
                floor = (go.m_Name, wp)
            meshes.append(m)
        if not meshes:
            raise StageError("무대에 그릴 메시가 없습니다")
        if floor is None:
            raise StageError("무대 바닥을 찾지 못했습니다")
        for m in meshes:
            if m["name"] == floor[0]:
                m["floor"] = True
        allp = np.concatenate(pts)
        lo, hi = allp.min(0), allp.max(0)
        fw = floor[1]
        stage = {
            "name": "rebirth", "prefab": PREFAB,
            "floor_y": float(fw[:, 1].max()),
            "floor_radius": float(np.sqrt(fw[:, 0] ** 2 + fw[:, 2] ** 2).max()),
            "radius": float(np.sqrt(allp[:, 0] ** 2 + allp[:, 2] ** 2).max()),
            "bounds": {"min": [float(-hi[0]), float(lo[1]), float(lo[2])],
                       "max": [float(-lo[0]), float(hi[1]), float(hi[2])]},
            "floor_mesh": floor[0],
            "reflection": {"meshes": [m["name"] for m in meshes if m.get("reflect")], "clip_plane_offset": clip},
            "lighting": {"lights": self._lights(root, by_id, world), "ambient_sh": self.ambient_sh()},
        }
        return E.Exporter.write(out_json, out, nodes, meshes, mats, {"stage": stage})

    def _material(self, ptr, mats: list, seen: dict) -> int | None:
        if ptr is None or not ptr.m_PathID:
            return None
        try:
            m = ptr.deref().read()
        except Exception as e:
            T.problem("무대 재질을 읽지 못했습니다", e)
            return None
        if m.m_Name in seen:
            return seen[m.m_Name]
        sp = m.m_SavedProperties
        maps, st, cubes = {}, {}, {}
        for k, v in sp.m_TexEnvs:
            if not v.m_Texture.m_PathID:
                continue
            try:
                o = v.m_Texture.deref()
                t = o.read()
                if o.type.name == "Texture2D":
                    maps[k] = self.tex.save(t)
                elif o.type.name == "Cubemap":
                    cubes[k] = self._cube(t)
                else:
                    continue
            except Exception as e:   # 그 그림만 빼고 그린다
                T.problem("무대 그림을 꺼내지 못했습니다", e)
                continue
            st[k] = [float(v.m_Scale.x), float(v.m_Scale.y), float(v.m_Offset.x), float(v.m_Offset.y)]
        cols = {k: [float(c.r), float(c.g), float(c.b), float(c.a)] for k, c in sp.m_Colors}
        floats = {k: float(x) for k, x in (getattr(sp, "m_Floats", None) or [])}
        ints = {k: int(x) for k, x in (getattr(sp, "m_Ints", None) or [])}
        shader = A.shader_name(m)
        d = {"name": m.m_Name, "kind": "stage", "shader": shader, "tex": maps.get("_BaseMap"),
             "color": E.hex_color(dict(sp.m_Colors)["_BaseColor"]) if "_BaseColor" in cols else "#FFFFFF",
             "maps": maps, "st": st, "colors": cols, "floats": floats,
             "kw": list(getattr(m, "m_ValidKeywords", None) or []),
             "reflect": bool(shader and "PlanarReflection" in shader)}
        if ints:
            d["ints"] = ints
        if cubes:
            d["cubes"] = {k: v for k, v in cubes.items() if v}
        mats.append(d)
        seen[m.m_Name] = len(mats) - 1
        return len(mats) - 1

    def _cube(self, t) -> dict:
        """큐브맵 → 면 6장 tex/<이름>_<면>.png (CUBE_SIZE). 못 풀면 오류를 올린다."""
        from PIL import Image
        from UnityPy.export import Texture2DConverter as TC
        name = T.tex_name(t)
        faces = [f"{name}_{f}" for f in CUBE_FACES]
        files = [self.tex.path(f) for f in faces]
        if not all(f.exists() for f in files):
            with T.lock(files[0]):
                if not all(f.exists() for f in files):
                    data = bytes(t.get_image_data())
                    step = len(data) // 6
                    rd = t.object_reader
                    for i, f in enumerate(files):
                        # 행 순서는 저장된 그대로 (뒤집지 않음 — GPU 큐브맵에 그대로 올리는 순서)
                        img = TC.parse_image_data(data[i * step:(i + 1) * step], t.m_Width, t.m_Height,
                                                  t.m_TextureFormat, getattr(rd, "version", (0, 0, 0, 0)),
                                                  getattr(rd, "platform", 0), getattr(t, "m_PlatformBlob", None),
                                                  flip=False).convert("RGB")
                        if img.width > CUBE_SIZE:
                            img = img.resize((CUBE_SIZE, CUBE_SIZE), Image.LANCZOS)
                        save_image(f, img)
        return {"faces": faces, "size": min(CUBE_SIZE, int(t.m_Width)), "order": "unity"}


# ── 서비스 입구 ──
def export(mid: str, game_dir: Path, data_dir: Path, out_json: Path) -> dict:
    """MODELS 의 id 하나를 out_json 으로 꺼낸다."""
    if mid not in MODELS:
        raise StageError(f"모르는 모델: {mid}")
    st = StageExporter(game_dir, data_dir)
    if mid == "stage:rebirth":
        return st.export(out_json)
    try:
        lighting = st.lighting()
    except StageError:   # 무대를 못 읽어도 볼륨 프리셋은 낸다
        lighting = None
    meta = presets(game_dir, lighting)
    write_json(out_json, meta)
    return meta
