"""게임 AssetPackages 의 Unity 번들을 읽기만 한다 (드레스룸).

  AssetPackages\\index, Starter\\index   자산 경로 → (BlobKey, 묶음 안 번호) — ResourcesPackage 목차와 같은 형식
  NNNN.blob                             u32 ? | u32 n | 오프셋 × (n-8)/4 | 번들 0 (파일 위치 n) | 번들 1 … 평문 UnityFS 번들 이어 붙임
                                        (XOR·deflate 없음). 번호 0 번들은 오프셋 표 바로 뒤, 1 번부터는 표의 [번호-1].
                                        표 마지막 값은 끝 위치라 번들 길이는 UnityFS 머리의 size 로 자른다.

번들끼리는 내부 이름(CAB-…)으로 서로 가리킨다 (prefab·fbx → 머티리얼 → 텍스처). 번들 머리의 노드 이름만 읽어
'CAB 이름 → 번들' 표를 만들어 두고(수 초, 게임 목차가 바뀔 때만), 번들을 열 때 참조를 따라 같이 연다.
게임 파일은 필요한 번들 조각만 읽어 메모리에서 쓰고, 결과(메시·텍스처)는 export 가 데이터 폴더에 복사본으로 둔다.
"""
