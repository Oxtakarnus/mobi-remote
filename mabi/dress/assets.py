def _keep(p: str) -> bool:
    return (_KEEP in p or _KEEP_ITEM in p or _KEEP_NOISE in p or _KEEP_GEM in p
            or (_KEEP_ANIM in p and p.endswith(".fbx"))
            or ((_KEEP_MAT in p or _KEEP_LIT in p) and p.endswith(".mat"))
            or (any(k in p for k in _KEEP_PROP) and p.endswith((".mat", ".tga", ".png")))
            or (_KEEP_BG_SHADER in p and p.endswith(".shader"))
            or (p.rsplit("/", 1)[-1].startswith(_CHAR_TEX) and p.lower().endswith((".tga", ".png"))))


Bundle = tuple[str, int, int]   # (하위 폴더, BlobKey, 묶음 안 번호)


def _starts(fh) -> tuple[int, ...]:
    """묶음 안 번호 → 번들 시작 위치. [0] 은 오프셋 표 바로 뒤(파일 위치 n), [k] 는 표의 k-1 번째 값."""
    head = fh.read(8)
    n = struct.unpack_from("<I", head, 4)[0]
    return (n, *struct.unpack("<%dI" % ((n - 8) // 4), fh.read(n - 8)))


def _head(fh, start: int) -> tuple[int, int, int, int, int]:
    """UnityFS 머리 → (머리 끝, 전체 크기, 압축된 목록 크기, 목록 크기, 플래그)."""
    fh.seek(start)
    hd = fh.read(512)
    if hd[:8] != b"UnityFS\0":
        raise ValueError("UnityFS 번들이 아님")
    ver = struct.unpack_from(">I", hd, 8)[0]
    p = 12
    for _ in range(2):   # 플레이어 판, 엔진 판 (NUL 끝 문자열)
        p = hd.index(b"\0", p) + 1
    size, csz, usz, flags = struct.unpack_from(">qIII", hd, p)
    p += 20
    if ver >= 7:
        p = (p + 15) // 16 * 16
    return p, size, csz, usz, flags


def node_names(fh, start: int) -> list[str]:
    """번들 안 파일 이름들 (CAB-…) — 목록(blocksInfo)만 풀어 읽는다."""
    p, size, csz, usz, flags = _head(fh, start)
    fh.seek(start + size - csz if flags & 0x80 else start + p)
    blk = fh.read(csz)
    comp = flags & 0x3F
    if comp in (2, 3):
        import lz4.block
        blk = lz4.block.decompress(blk, uncompressed_size=usz)
    elif comp == 1:
        import lzma
        blk = lzma.LZMADecompressor(lzma.FORMAT_RAW, filters=[{"id": lzma.FILTER_LZMA1}]).decompress(blk)
    q = 16
    nb = struct.unpack_from(">i", blk, q)[0]
    q += 4 + nb * 10
    nn = struct.unpack_from(">i", blk, q)[0]
    q += 4
    names = []
    for _ in range(nn):
        q += 20
        e = blk.index(b"\0", q)
        names.append(blk[q:e].decode("utf-8", "replace"))
        q = e + 1
    return names


class AssetPack:
    """게임 AssetPackages 하나. cache_dir 에 CAB 표를 둔다 (목차가 바뀌면 다시 만든다).
    keep: 기억할 자산 경로 고르기. 기본은 캐릭터 자산 — 이펙트(fx)·무대(stage)는 자기 거르기와 CAB 표 폴더를 넘긴다
    (CAB 표 판은 같은 _CAB_VER), 아이콘(icons)은 경로만 쓰고 cabs() 는 부르지 않는다."""

    def __init__(self, game_dir: Path, cache_dir: Path, keep=_keep):
        self.root = Path(game_dir) / "AssetPackages"
        self.cache_dir = Path(cache_dir)
        self.paths: dict[str, Bundle] = {}
        for sub in SUBS:
            idx = self.root / sub / "index"
            for path, (bk, ix) in gf.parse_index(idx.read_bytes(), keep).items():
                self.paths[path] = (sub, bk, ix)
        self._cab: dict[str, Bundle] | None = None
        self._extra: dict[str, Bundle] | None = None   # 거른 표 밖에서 찾은 CAB (cab_extra.json)
        self._all: dict[str, Bundle] | None = None     # 전체 목차 CAB 표 (못 찾은 CAB 이 생겼을 때 한 번, 메모리에만)
        self._all_lock = threading.Lock()

    def stamp(self) -> list[int]:
        return [v for sub in SUBS for v in gf.stamp_of(self.root / sub / "index")]

    def blob(self, b: Bundle) -> Path:
        return self.root / b[0] / ("%04d.blob" % (b[1] & 0x7FFF))

    def read(self, b: Bundle) -> bytes:
        with open(self.blob(b), "rb") as fh:
            start = _starts(fh)[b[2]]
            _, size, *_ = _head(fh, start)
            fh.seek(start)
            return fh.read(size)

    # ── CAB 이름 → 번들 ──
    def cabs(self) -> dict[str, Bundle]:
        if self._cab is None:
            f = self.cache_dir / "cab.json"
            stamp = self.stamp()
            try:
                d = json.loads(f.read_text(encoding="utf-8"))
                if d.get("stamp") == stamp and d.get("ver") == _CAB_VER:
                    self._cab = {k: tuple(v) for k, v in d["cab"].items()}
            except (OSError, ValueError, KeyError):
                pass
            if self._cab is None:
                self._cab = self._scan()
                write_json(f, {"stamp": stamp, "ver": _CAB_VER, "cab": self._cab})
        return self._cab

    def cab(self, name: str) -> Bundle | None:
        """CAB 이름 → 번들. 거른 표에 없으면 전체 목차를 한 번 훑어 찾고, 찾은 것은 cab_extra.json 에 남긴다 —
        캐릭터 폴더 밖 재질·그림을 빌려 쓰는 옷이 있다 (사물 머리·풍등·해적 모자가 배경 소품 재질, 패션 무기가 마네킹 재질)."""
        name = name.lower()
        b = self.cabs().get(name)
        if b is not None:
            return b
        with self._all_lock:
            f = self.cache_dir / "cab_extra.json"
            stamp = self.stamp()
            if self._extra is None:
                self._extra = {}
                try:
                    d = json.loads(f.read_text(encoding="utf-8"))
                    if d.get("stamp") == stamp:
                        self._extra = {k: tuple(v) for k, v in d["cab"].items()}
                except (OSError, ValueError, KeyError):
                    pass
            if name in self._extra:
                return self._extra[name]
            if self._all is None:
                every: dict[str, Bundle] = {}
                for sub in SUBS:
                    idx = self.root / sub / "index"
                    for path, (bk, ix) in gf.parse_index(idx.read_bytes(), lambda p: True).items():
                        every[path] = (sub, bk, ix)
                self._all = self._scan(every.values())
            b = self._all.get(name)
            if b is not None:
                self._extra[name] = b
                write_json(f, {"stamp": stamp, "cab": self._extra})
            return b

    def _scan(self, bundles=None) -> dict[str, Bundle]:
        by_blob: dict[tuple[str, int], set[int]] = {}
        for sub, bk, ix in (self.paths.values() if bundles is None else bundles):
            by_blob.setdefault((sub, bk), set()).add(ix)
        out = {}
        for (sub, bk), ixs in by_blob.items():
            with open(self.blob((sub, bk, 0)), "rb") as fh:
                starts = _starts(fh)
                for ix in ixs:
                    try:
                        for nm in node_names(fh, starts[ix]):
                            out[nm.lower()] = (sub, bk, ix)
                    except Exception:   # 깨진 번들 하나 때문에 표 전체를 버리지 않는다
                        continue
        return out

    # ── 열기 ──
    def open(self, paths, limit: int = 40):
        """자산 경로들의 번들을 참조를 따라 같이 연 UnityPy Environment. limit 개 번들까지만."""
        import UnityPy
        env = UnityPy.Environment()
        todo: list[Bundle] = [self.paths[p] for p in paths]
        done: set[Bundle] = set()
        seen_files: set[int] = set()
        while todo and len(done) < limit:
            b = todo.pop(0)
            if b in done:
                continue
            done.add(b)
            # 이름을 꼭 준다 — 안 주면 UnityPy 가 BytesIO 의 hash(메모리 주소)로 이름을 지어, 앞 BytesIO 가 풀린
            # 자리에 새것이 생기면 같은 이름으로 앞 번들을 덮어쓴다 (prefab 을 못 찾는 일이 가끔 생겼다)
            env.load_file(io.BytesIO(self.read(b)), name="bundle-%s-%d-%d" % b)
            for f in list(env.files.values()):
                for sf in getattr(f, "files", {}).values():
                    if id(sf) in seen_files:
                        continue
                    seen_files.add(id(sf))
                    for ext in getattr(sf, "externals", ()):
                        nb = self.cab(ext.path.rsplit("/", 1)[-1])
                        if nb and nb not in done and nb not in todo:
                            todo.append(nb)
        return env


def shader_name(mat) -> str | None:
    """머티리얼의 셰이더 이름 (MMN/BG/Water 꼴). 셰이더를 못 풀면 번들 목록의 자산 경로, 셰이더 번들이 안 열렸으면 None."""
    sh = getattr(mat, "m_Shader", None)
    if not sh or not sh.m_PathID:
        return None
    try:
        obj = sh.deref()
    except Exception:
        return None
    try:
        return obj.read().m_ParsedForm.m_Name
    except Exception:
        pass
    try:   # 셰이더를 못 풀면 번들 목록의 자산 경로로
        for o in obj.assets_file.objects.values():
            if o.type.name == "AssetBundle":
                for k, info in o.read().m_Container:
                    if info.asset.m_PathID == sh.m_PathID:
                        return k
    except Exception:
        pass
    return None


def objects(env, path: str, kind: str) -> list:
    """번들 목록(AssetBundle.m_Container)에서 path 자산 중 kind(GameObject·Texture2D…) 것들을 읽어서."""
    out = []
    want = path.lower()
    for o in env.objects:
        if o.type.name != "AssetBundle":
            continue
        for k, info in o.read().m_Container:
            if k.lower() != want:
                continue
            try:
                a = info.asset.deref()
            except Exception:
                continue
            if a.type.name == kind:
                out.append(a.read())
    return out


def roots(env, path: str) -> list:
    """path 자산의 GameObject 들 — 한 번들에 여러 fbx 가 들어 있다."""
    return objects(env, path, "GameObject")


def _linked(go):
    """GameObject 의 컴포넌트 (가리킴, ObjectReader) 짝 — 못 따라가는 칸은 건너뛴다.
    m_Component 칸은 UnityPy 판에 따라 {component: 가리킴} 이거나 (클래스 id, 가리킴) 짝이다."""
    for comp in go.m_Component:
        ptr = getattr(comp, "component", None) or (comp[1] if isinstance(comp, tuple) else comp)
        try:
            yield ptr, ptr.deref()
        except Exception:
            continue


def components(go):
    """GameObject 의 컴포넌트 ObjectReader 들 (옷·흔들림·무대·이펙트가 같이 쓴다)."""
    for _ptr, o in _linked(go):
        yield o


def component_ptr(go, type_name: str):
    """GameObject 의 그 종류 첫 컴포넌트 가리킴 (없으면 None)."""
    return next((p for p, o in _linked(go) if o.type.name == type_name), None)


def script_name(o) -> str | None:
    """MonoBehaviour ObjectReader 의 스크립트 클래스 이름 (못 읽으면 None)."""
    try:
        return o.read().m_Script.deref().read().m_ClassName
    except Exception:
        return None


def renderers(go) -> list[tuple]:
    """GameObject 아래 (GameObject, 렌더러) 전부."""
    out = []

    def walk(g):
        for o in components(g):
            tn = o.type.name
            if tn in ("SkinnedMeshRenderer", "MeshRenderer"):
                out.append((g, o.read()))
            elif tn == "Transform":
                for ch in o.read().m_Children:
                    try:
                        walk(ch.deref().read().m_GameObject.deref().read())
                    except Exception:
                        continue
    walk(go)
    return out
